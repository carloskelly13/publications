import { createHash } from 'node:crypto'
import { and, asc, count, desc, eq, gt, lt, notInArray } from 'drizzle-orm'
import { drizzle } from 'drizzle-orm/postgres-js'
import postgres from 'postgres'
import { config } from './config.js'
import { appSessions, documents, pages, schema, shapes, users } from './schema.js'
import type { DocumentInput, ShapeInputType } from './schemas.js'

export type CurrentUser = {
  id: string
  googleSubject: string
  email: string
  name: string
}

export type Session = {
  tokenHash: string
  csrfToken: string
  user: CurrentUser
}

const createDatabase = () => {
  const client = postgres(config.databaseUrl, {
    max: Number(process.env.DATABASE_MAX_POOL_SIZE ?? 5),
    idle_timeout: 20,
    connect_timeout: 10,
    prepare: false,
  })
  return { client, db: drizzle(client, { schema }) }
}

type Database = ReturnType<typeof createDatabase>['db']
type Transaction = Parameters<Parameters<Database['transaction']>[0]>[0]

let connection: ReturnType<typeof createDatabase> | undefined
let initialization: Promise<void> | undefined

const getConnection = () => {
  connection ??= createDatabase()
  return connection
}

export const getDatabase = () => getConnection().db

export const hashToken = (token: string): string => createHash('sha256').update(token).digest('hex')

export const initializeDatabase = (): Promise<void> => {
  initialization ??= (async () => {
    const { client } = getConnection()
    await client.begin(async (tx) => {
      await tx`select pg_advisory_xact_lock(707808800)`
      await tx`
        create table if not exists users (
          id bigint generated by default as identity primary key,
          google_subject varchar(255) not null unique,
          email varchar(320) not null,
          display_name varchar(255) not null
        )
      `
      await tx`
        create table if not exists documents (
          id bigint generated by default as identity primary key,
          user_id bigint not null references users(id),
          created_at timestamp with time zone not null default current_timestamp,
          updated_at timestamp with time zone not null default current_timestamp,
          name varchar(255)
        )
      `
      await tx`
        create table if not exists pages (
          id bigint generated by default as identity primary key,
          document_id bigint not null references documents(id) on delete cascade,
          page_number integer,
          width double precision,
          height double precision
        )
      `
      await tx`
        create table if not exists shapes (
          id bigint generated by default as identity primary key,
          page_id bigint not null references pages(id) on delete cascade,
          type varchar(255), width double precision, height double precision,
          x double precision, y double precision, path_geometry jsonb,
          z integer, r double precision,
          fill varchar(255), fill_opacity double precision, stroke varchar(255),
          stroke_width double precision, stroke_opacity double precision, text text,
          rotation double precision not null default 0,
          radius_top_left double precision not null default 0,
          radius_top_right double precision not null default 0,
          radius_bottom_right double precision not null default 0,
          radius_bottom_left double precision not null default 0,
          rich_text_content jsonb,
          content_version integer not null default 1
        )
      `
      await tx`alter table shapes add column if not exists path_geometry jsonb`
      await tx`
        create table if not exists app_sessions (
          token_hash varchar(64) primary key,
          user_id bigint not null references users(id) on delete cascade,
          csrf_token varchar(64) not null,
          created_at timestamp with time zone not null default current_timestamp,
          last_accessed_at timestamp with time zone not null default current_timestamp,
          expires_at timestamp with time zone not null
        )
      `
      await tx`create index if not exists documents_user_id_idx on documents(user_id)`
      await tx`create index if not exists pages_document_id_idx on pages(document_id)`
      await tx`create index if not exists shapes_page_id_idx on shapes(page_id)`
      await tx`create index if not exists app_sessions_expires_at_idx on app_sessions(expires_at)`
    })
  })().catch((error) => {
    initialization = undefined
    throw error
  })
  return initialization
}

export async function provisionUser({
  subject,
  email,
  name,
}: {
  subject: string
  email: string
  name: string
}): Promise<CurrentUser> {
  await initializeDatabase()
  const [row] = await getDatabase()
    .insert(users)
    .values({ googleSubject: subject, email, displayName: name })
    .onConflictDoUpdate({
      target: users.googleSubject,
      set: { email, displayName: name },
    })
    .returning()
  if (!row) {
    throw new Error('Google user could not be provisioned.')
  }
  return {
    id: row.id.toString(),
    googleSubject: row.googleSubject,
    email: row.email,
    name: row.displayName,
  }
}

export async function createSession({
  token,
  csrfToken,
  userId,
}: {
  token: string
  csrfToken: string
  userId: string
}): Promise<void> {
  await initializeDatabase()
  const db = getDatabase()
  await db.delete(appSessions).where(lt(appSessions.expiresAt, new Date()))
  await db.insert(appSessions).values({
    tokenHash: hashToken(token),
    userId: BigInt(userId),
    csrfToken,
    expiresAt: new Date(Date.now() + 7 * 24 * 60 * 60 * 1000),
  })
}

export async function findSession({ token }: { token: string }): Promise<Session | undefined> {
  await initializeDatabase()
  const db = getDatabase()
  const tokenHash = hashToken(token)
  const [row] = await db
    .select({ session: appSessions, user: users })
    .from(appSessions)
    .innerJoin(users, eq(users.id, appSessions.userId))
    .where(and(eq(appSessions.tokenHash, tokenHash), gt(appSessions.expiresAt, new Date())))
    .limit(1)
  if (!row) {
    return undefined
  }

  const hourAgo = new Date(Date.now() - 60 * 60 * 1000)
  if (row.session.lastAccessedAt < hourAgo) {
    await db
      .update(appSessions)
      .set({
        lastAccessedAt: new Date(),
        expiresAt: new Date(Date.now() + 7 * 24 * 60 * 60 * 1000),
      })
      .where(eq(appSessions.tokenHash, tokenHash))
  }

  return {
    tokenHash,
    csrfToken: row.session.csrfToken,
    user: {
      id: row.user.id.toString(),
      googleSubject: row.user.googleSubject,
      email: row.user.email,
      name: row.user.displayName,
    },
  }
}

export async function deleteSession({ token }: { token: string }): Promise<void> {
  await initializeDatabase()
  await getDatabase()
    .delete(appSessions)
    .where(eq(appSessions.tokenHash, hashToken(token)))
}

const shapeValues = ({
  pageId,
  shape,
}: {
  pageId: bigint
  shape: ShapeInputType
}): typeof shapes.$inferInsert => ({
  pageId,
  type: shape.type,
  width: shape.width,
  height: shape.height,
  x: shape.x,
  y: shape.y,
  pathGeometry: shape.pathGeometry,
  z: shape.z,
  radiusTopLeft: shape.radiusTopLeft ?? 0,
  radiusTopRight: shape.radiusTopRight ?? 0,
  radiusBottomRight: shape.radiusBottomRight ?? 0,
  radiusBottomLeft: shape.radiusBottomLeft ?? 0,
  rotation: shape.rotation ?? 0,
  fill: shape.fill,
  fillOpacity: shape.fillOpacity,
  stroke: shape.stroke,
  strokeWidth: shape.strokeWidth,
  strokeOpacity: shape.strokeOpacity,
  text: shape.text,
  richTextContent: shape.richTextContent,
  contentVersion: shape.contentVersion ?? 1,
})

async function replacePages({
  tx,
  documentId,
  input,
}: {
  tx: Transaction
  documentId: bigint
  input: DocumentInput
}): Promise<void> {
  const existing = await tx
    .select({ id: pages.id })
    .from(pages)
    .where(eq(pages.documentId, documentId))
  const existingIds = new Set(existing.map(({ id }) => id.toString()))
  const retainedIds: bigint[] = []

  for (const page of input.pages) {
    const requestedId = page.id === undefined ? undefined : String(page.id)
    let pageId: bigint
    if (requestedId && existingIds.has(requestedId)) {
      pageId = BigInt(requestedId)
      await tx
        .update(pages)
        .set({ pageNumber: page.pageNumber, width: page.width, height: page.height })
        .where(and(eq(pages.id, pageId), eq(pages.documentId, documentId)))
    } else {
      const [created] = await tx
        .insert(pages)
        .values({
          documentId,
          pageNumber: page.pageNumber,
          width: page.width,
          height: page.height,
        })
        .returning({ id: pages.id })
      if (!created) {
        throw new Error('Page could not be created.')
      }
      pageId = created.id
    }

    retainedIds.push(pageId)
    await tx.delete(shapes).where(eq(shapes.pageId, pageId))
    const newShapes = (page.shapes ?? []).map((shape) => shapeValues({ pageId, shape }))
    if (newShapes.length > 0) {
      await tx.insert(shapes).values(newShapes)
    }
  }

  const ownedPages = eq(pages.documentId, documentId)
  await tx
    .delete(pages)
    .where(
      retainedIds.length === 0 ? ownedPages : and(ownedPages, notInArray(pages.id, retainedIds)),
    )
}

